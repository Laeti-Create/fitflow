import {test,expect} from '@playwright/test';
test('local programme workflow persists and clears private draft on signout',async({page,request})=>{
  const unexpected=[];
  page.on('pageerror',error=>console.error('Browser error:',error.message));
  page.on('requestfailed',req=>console.error('Request failed:',new URL(req.url()).hostname,req.failure()?.errorText));
  page.on('request',req=>{if(/firestore.googleapis.com|identitytoolkit.googleapis.com/.test(req.url()) && !req.url().startsWith('http://127.0.0.1')) unexpected.push(req.url());});
  await page.goto('/');
  await page.getByRole('button',{name:'Se connecter avec Alice (test)',exact:true}).click();
  await expect(page.locator('#screen-app')).toHaveClass(/active/);
  await page.locator('[data-nav=settings]').click();
  const profile=page.locator('#hybrid-profile');
  await profile.locator('[name=adult]').check();
  await profile.locator('[name=goals][value=strength]').check();
  await profile.locator('[name=days][value="2"]').check();
  await profile.locator('[name=strengthDays]').fill('1');await profile.locator('[name=runDays]').fill('0');
  await profile.locator('[name=minutes]').fill('45');await profile.locator('[name=equipment]').fill('Haltères');
  await profile.locator('[name=recentTraining]').fill('Débutante fictive');
  await profile.getByRole('button',{name:'Vérifier et enregistrer'}).click();
  await expect(page.locator('#hybrid-profile-result')).toContainText('Questionnaire enregistré');
  await profile.locator('[name=equipment]').fill('Modification non enregistrée');
  await page.locator('#hybrid-load-profile').click();
  await expect(profile.locator('[name=equipment]')).toHaveValue('Haltères');
  await page.getByText('2. Musculation · séries réalisées',{exact:true}).click();
  const set=page.locator('#hybrid-set');await set.locator('[name=exercise]').fill('<img src=x onerror=alert(1)>');await set.locator('[name=reps]').fill('10');await set.locator('[name=loadKg]').fill('20');
  await set.getByRole('button').click();await expect(page.locator('#hybrid-sets li')).toHaveCount(1);await expect(page.locator('#hybrid-sets img')).toHaveCount(0);
  await page.locator('#hybrid-strength-save [name=name]').fill('Séance fictive');await page.locator('#hybrid-strength-save button').click();await expect(page.locator('#hybrid-strength-result')).toContainText('Séance enregistrée');
  await page.getByText('3. Running · calendrier',{exact:true}).click();
  await page.locator('#hybrid-import input').setInputFiles('tests/calendar.fixture.json');await page.locator('#hybrid-import button').click();await expect(page.locator('#hybrid-calendar-preview')).toContainText('nouvelle(s)');
  await page.locator('#hybrid-import-confirm').click();await expect(page.locator('#hybrid-calendar-result')).toContainText('au calendrier');
  await page.getByText('4. Nutrition · cible du jour',{exact:true}).click();
  const target=page.locator('#hybrid-target');await target.locator('[name=date]').fill('2026-10-14');await target.locator('[name=easyKcal]').fill('1900');await target.locator('[name=easyProtein]').fill('100');await target.locator('button').click();await expect(page.locator('#hybrid-target-result')).toContainText('1900 kcal');
  await page.getByText('5. Récupération · mon journal',{exact:true}).click();
  await page.locator('#hybrid-recovery button').click();await expect(page.locator('#hybrid-recovery-result')).toContainText('3 champ(s) non renseigné(s)');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.locator('#btn-signout').click();await expect(page.locator('#hybrid-workspace')).toHaveCount(0);
  expect(unexpected).toEqual([]);
  for(const path of ['/.env.local','/node_modules/firebase/package.json','/security/firestore.candidate.rules','/package-lock.json']) expect((await request.get(path)).status()).toBe(404);
});
